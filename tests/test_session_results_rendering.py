r"""`scripts/render_session_results.py` reproduces the committed session files exactly.

Arm A's session 1 and session 2 raw results files were assembled by hand. This
pins the renderer against them: regenerate both, assert byte-equality with what
is committed in `reports/raw/`. If the renderer drifts -- a changed percentile
method, a different clock, a reordered section -- these fail. Session 3 is pinned
too, but see `SESSIONS`: it can only pin stability, since the renderer produced it.

`scripts/distil_session_fixture.py`, which produces the fixtures these tests run
from, is pinned here as well -- otherwise the next session's fixture could be
built by a drifted distiller and nothing would notice.

**Why this is not circular.** The committed files predate the renderer and were
produced independently of it. A distillation that dropped or corrupted a field,
or a renderer that computed a number a different way, would stop matching them.
Agreement is evidence precisely because the two were arrived at separately.

**Why a distilled fixture rather than the real roots.** The renderer's inputs are
the session roots on the measurement host (`/root/aep-phase13/...`), ~150 MB of
raw run data that `.gitignore` excludes by policy and CI has no access to. A test
gated on their presence would skip in CI, and `scripts/check_pytest_gates.py`
gate 1 is *zero skipped* -- "36 skipped = green" is the failure mode it exists to
prevent. So the handful of fields the renderer actually reads are distilled into
`tests/fixtures/session-results/*.json` (~56 KB each) and the run tree is
materialised in a tmp dir. The test always runs.

A consequence worth stating: the materialised tree has fresh mtimes, unrelated to
the original collection order. That the output still matches byte-for-byte is an
independent check that the renderer does not use directory mtimes -- the trap
`docs/30-controlled-fault-mechanism.md` records as having produced a nonsense
rate on the first attempt at this measurement.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from scripts.distil_session_fixture import distil, serialise
from scripts.render_session_results import render

REPO_ROOT = Path(__file__).resolve().parent.parent
FIXTURES = REPO_ROOT / "tests" / "fixtures" / "session-results"
COMMITTED = REPO_ROOT / "reports" / "raw"

#: (fixture, the committed file it must reproduce).
#:
#: s1 and s2 are the *independent* checks: hand-assembled before this renderer
#: existed, so agreement is evidence the renderer computes the right numbers.
#: s3 was generated BY the renderer, so it can only ever pin stability, not
#: correctness -- it is here so a later change cannot silently rewrite it.
SESSIONS = [
    ("armA-s1.json", "phase13-armA-s1-results.txt"),
    ("armA-s2.json", "phase13-armA-s2-results.txt"),
    ("armA-s3.json", "phase13-armA-s3-results.txt"),
]

#: Of those, the ones whose agreement is independent evidence.
INDEPENDENT = {"phase13-armA-s1-results.txt", "phase13-armA-s2-results.txt"}


def materialise(fixture: dict, destination: Path) -> Path:
    """Rebuild the minimal session tree the renderer reads."""
    for entry in fixture["runs"]:
        run = destination / entry["name"]
        run.mkdir(parents=True)

        if entry["has_run_config"]:
            (run / "run-config.json").write_text(
                json.dumps(
                    {
                        "environment": {
                            "redis_fault_mechanism": entry["redis_fault_mechanism"]
                        }
                    }
                ),
                encoding="utf-8",
            )

        if entry["runner_wall_ms"] is not None:
            (run / "events-runner.jsonl").write_text(
                json.dumps(
                    {"event": "clock_reference", "wall_ms": entry["runner_wall_ms"]}
                )
                + "\n",
                encoding="utf-8",
            )

        # The kill events, in the count and polarity the original recorded. A run
        # the harness refused contributes none, which is what drives the
        # "runs with no kill event" line.
        kills = [
            json.dumps({"event": "redis_kill_issued", "paused": True})
            for _ in range(entry["kill_paused_true"])
        ] + [
            json.dumps({"event": "redis_kill_issued", "paused": False})
            for _ in range(entry["kill_paused_false"])
        ]
        if kills:
            (run / "events-worker-0-attempt-1.jsonl").write_text(
                "\n".join(kills) + "\n", encoding="utf-8"
            )

    analysis = destination / "analysis"
    analysis.mkdir(parents=True)
    (analysis / "coverage.json").write_text(
        json.dumps(fixture["coverage"]), encoding="utf-8"
    )
    (analysis / "redis-kill-ablation.csv").write_text(
        fixture["ablation_csv"], encoding="utf-8"
    )

    (destination / "matrix-progress.jsonl").write_text(
        "\n".join(json.dumps(record) for record in fixture["progress"]) + "\n",
        encoding="utf-8",
    )
    return destination


@pytest.fixture
def session(request, tmp_path) -> tuple[Path, str]:
    fixture_name, committed_name = request.param
    fixture = json.loads((FIXTURES / fixture_name).read_text(encoding="utf-8"))
    root = materialise(fixture, tmp_path / fixture["source_root"])
    return root, committed_name


@pytest.mark.parametrize("session", SESSIONS, indirect=True, ids=["s1", "s2", "s3"])
def test_the_renderer_reproduces_the_committed_file_byte_for_byte(session):
    root, committed_name = session
    expected = (COMMITTED / committed_name).read_text(encoding="utf-8")

    assert render(root) == expected, (
        f"{committed_name} is no longer reproducible from its session data. "
        "Either the renderer changed or the committed file was hand-edited; "
        "both need a human before any session file is regenerated."
    )


@pytest.mark.parametrize("session", SESSIONS, indirect=True, ids=["s1", "s2", "s3"])
def test_rendering_is_deterministic(session):
    """Two renders of one tree agree -- no dict-ordering or filesystem-order leak."""
    root, _ = session

    assert render(root) == render(root)


def test_every_committed_arm_a_session_file_has_a_fixture():
    """A new session file added without a fixture would silently go unpinned."""
    committed = {
        path.name
        for path in COMMITTED.glob("phase13-armA-s*-results.txt")
        # VOIDED collections are not reproducible: the root is retained as
        # evidence, not as a regenerable artifact.
        if "VOID" not in path.name
    }
    pinned = {committed_name for _, committed_name in SESSIONS}

    assert committed == pinned, (
        "Arm A session results files and their fixtures have diverged. "
        f"committed with no fixture: {sorted(committed - pinned)}; "
        f"fixture with no committed file: {sorted(pinned - committed)}"
    )


@pytest.mark.parametrize(
    ("fixture_name", "_committed_name"), SESSIONS, ids=["s1", "s2", "s3"]
)
def test_distilling_a_session_root_reproduces_the_committed_fixture(
    fixture_name, _committed_name, tmp_path
):
    """`scripts/distil_session_fixture.py` is pinned to its own output.

    The fixtures are what lets the renderer be tested without the ~150 MB session
    roots. If the distiller drifts -- a dropped field, a changed JSON indent, a
    different sort -- the fixtures it produces for the next session would silently
    stop being comparable with the committed ones. This catches that.

    **What this cannot check.** The session root here is materialised from the
    fixture, so it is a faithful but simplified stand-in: one events file holding
    the kill records, one line in `events-runner.jsonl`, no fields the distiller
    ignores. It pins field extraction and the exact serialisation, not the
    distiller's behaviour against a real collection tree. That check is the CLI's
    `--check` mode, run on the measurement host where the roots exist::

        python scripts/distil_session_fixture.py \
            --root /root/aep-phase13/armA-s1-2026-09-03 \
            --check tests/fixtures/session-results/armA-s1.json

    All three Arm A sessions were verified that way when the script was promoted.
    """
    committed = (FIXTURES / fixture_name).read_text(encoding="utf-8")
    fixture = json.loads(committed)
    # The directory name is itself distilled, as `source_root`.
    root = materialise(fixture, tmp_path / fixture["source_root"])

    assert serialise(distil(root)) == committed, (
        f"{fixture_name} is no longer reproducible by the distiller. The "
        "renderer tests above still pass against the committed fixture, so the "
        "fixtures and the script that makes them have diverged."
    )


def test_at_least_two_sessions_are_independent_evidence():
    """The renderer's correctness rests on files it did not produce.

    If s1 and s2 were ever regenerated by this renderer and re-committed, every
    remaining check would be the renderer agreeing with itself.
    """
    pinned = {committed_name for _, committed_name in SESSIONS}

    assert INDEPENDENT <= pinned
    assert len(INDEPENDENT) >= 2
